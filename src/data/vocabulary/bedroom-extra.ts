import type { Level, VocabularyWord } from '../../types/game';

// Bedroom word bank, A1–B2. One row = one word:
//
//   w('English', 'level', 'category', 'linked 3D object or null', 'Russian', 'Ukrainian')
//
// The linked object matters: when a student practises with that object in the room,
// the game asks translation and spelling questions about these words — but only
// words at or below the student's level (set in the menu).
// Words with null still appear in the Word Book and as wrong answer options.

function w(word: string, level: Level, category: string, objectId: string | null, ru: string, uk: string): VocabularyWord {
  return {
    id: word.toLowerCase().replace(/[^a-z]+/g, '-'),
    word,
    level,
    topic: 'bedroom',
    category,
    objectId: objectId ?? undefined,
    translations: { ru, uk },
  };
}

